// CompareFaceEmbeddings calculates cosine similarity between two face embeddings
func (f *FacialRecognitionService) CompareFaceEmbeddings(embedding1, embedding2 []float64) float64 {
	if len(embedding1) != len(embedding2) {
		return 0.0
	}

	// Cosine similarity = (A · B) / (||A|| * ||B||)
	dotProduct := 0.0
	normA := 0.0
	normB := 0.0

	for i := range embedding1 {
		dotProduct += embedding1[i] * embedding2[i]
		normA += embedding1[i] * embedding1[i]
		normB += embedding2[i] * embedding2[i]
	}

	if normA == 0 || normB == 0 {
		return 0.0
	}

	return dotProduct / (math.Sqrt(normA) * math.Sqrt(normB))
}

